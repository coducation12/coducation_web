/**
 * 주어진 날짜(YYYY-MM-DD 형식)의 한국 공휴일 명칭을 리턴합니다.
 * 공휴일이 아니면 null을 리턴합니다.
 */
export function getHoliday(dateStr: string): string | null {
    if (!dateStr) return null;
    
    // 1. 매년 변동되는 음력 공휴일 및 대체 공휴일 확인
    if (VARIABLE_HOLIDAYS[dateStr]) {
        return VARIABLE_HOLIDAYS[dateStr];
    }
    
    // 2. 양력 고정 공휴일 확인 (MM-DD)
    const mmDd = dateStr.substring(5); // "YYYY-MM-DD" -> "MM-DD"
    if (FIXED_HOLIDAYS[mmDd]) {
        return FIXED_HOLIDAYS[mmDd];
    }
    
    return null;
}
